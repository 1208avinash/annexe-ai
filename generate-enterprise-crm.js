import BusinessAnalyzer from "./api/factory/business-analyzer.js";
import BlueprintValidator from "./api/factory/blueprint-validator.js";
import ProjectExecutor from "./api/factory/project-executor.js";
import SoftwareFactory from "./api/factory/software-factory.js";
import TemplateCompiler from "./api/factory/template-compiler.js";
import SoftwareArchitect from "./api/architecture/software-architect.js";
import PlanningDecisionAdapter from "./api/architecture/planning-decision-adapter.js";
import PlanningEngine from "./api/planning-engine/planning-engine.js";
import WorkflowGenerator from "./api/workflow/workflow-generator.js";
import WorkflowGraph from "./api/engineering/workflow-graph.js";
import TaskScheduler from "./api/engineering/task-scheduler.js";
import ParallelExecutor from "./api/engineering/parallel-executor.js";
import EngineeringDirector from "./api/engineering/engineering-director.js";
import ProjectWriter from "./api/project-writer/project-writer.js";
import { execSync } from "child_process";
import path from "path";

const workspaceRoot = "workspace";

const businessAnalyzer = new BusinessAnalyzer();
const templateCompiler = new TemplateCompiler();
const blueprintValidator = new BlueprintValidator();
const softwareArchitect = new SoftwareArchitect();
const engineeringDirector = new EngineeringDirector();
const planningDecisionAdapter = new PlanningDecisionAdapter();
const planningEngine = new PlanningEngine();
const workflowGenerator = new WorkflowGenerator();
const workflowGraph = new WorkflowGraph();
const taskScheduler = new TaskScheduler();
const parallelExecutor = new ParallelExecutor({ engineeringDirector });
const projectWriter = new ProjectWriter({ workspaceRoot });

const projectExecutor = new ProjectExecutor({
    businessAnalyzer,
    templateCompiler,
    blueprintValidator,
    softwareArchitect,
    engineeringDirector,
    planningDecisionAdapter,
    planningEngine,
    workflowGenerator,
    workflowGraph,
    taskScheduler,
    parallelExecutor,
    projectWriter
});

const softwareFactory = new SoftwareFactory({
    projectExecutor
});

const request = {
    requestType: "buildSoftware",
    project: {
        projectId: "enterprise-crm",
        name: "Enterprise CRM",
        description: "First enterprise CRM generated by ANNEXE AI",
        industry: "CRM"
    },
    challenge: "Need an enterprise CRM for customers, leads, and sales pipeline automation",
    solution: "Generate a production-ready CRM scaffold with backend, frontend, and deployment files",
    requirements: [
        "Authentication",
        "Dashboard",
        "Customers",
        "Leads",
        "Reporting",
        "Notifications",
        "Automation"
    ]
};

console.log("Generating enterprise CRM into workspace/enterprise-crm ...");

const result = await softwareFactory.buildSoftware(request);

if (!result.success) {
    console.error("Enterprise CRM generation failed.");
    console.error(result.error ?? result.message ?? "Unknown error");
    process.exit(1);
}

console.log("Enterprise CRM generation completed.");
console.log(`Project ID: ${result.project?.projectId ?? "unknown"}`);
console.log(`Output: ${result.project?.outputDirectory ?? "workspace/enterprise-crm"}`);
console.log(`Files written: ${result.report?.filesWritten ?? 0}`);
console.log(`Final status: ${result.pipeline?.finalStatus ?? "unknown"}`);

const projectRoot = path.join("workspace", result.project?.projectId ?? "enterprise-crm");
const frontendRoot = path.join(projectRoot, "frontend");

console.log("Running backend validation: python -m compileall backend");
execSync("python -m compileall backend", {
    cwd: projectRoot,
    stdio: "inherit"
});

console.log("Running frontend validation: npm install");
execSync("npm install --no-fund --no-audit", {
    cwd: frontendRoot,
    stdio: "inherit"
});

console.log("Running frontend validation: npm run build");
execSync("npm run build", {
    cwd: frontendRoot,
    stdio: "inherit"
});

console.log("Build validation completed.");
