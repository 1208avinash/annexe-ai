import BuildManifestGenerator
    from "./lib/workers/build-manifest-generator.js";

console.log("\n═══════════════════════════════════════════════");
console.log(" ANNEXE AI — Build Manifest Generator Test");
console.log("═══════════════════════════════════════════════\n");

try {

    const generator =
        new BuildManifestGenerator();

    const manifest =
        generator.generate({

            projectId: "PROJECT-001",

            executionId: "EXEC-001",

            task: {

                taskId: "TASK-001",

                title: "Create Login Page"

            },

            generatedBy: "AI Engineer",

            files: [

                {

                    path:
                        "frontend/src/pages/Login.jsx",

                    type:
                        "react-component",

                    language:
                        "javascript",

                    content:
                        "export default function Login(){ return <div>Login</div>; }"

                },

                {

                    path:
                        "frontend/src/pages/Login.css",

                    type:
                        "stylesheet",

                    language:
                        "css",

                    content:
                        ".login { display:flex; }"

                },

                {

                    path:
                        "frontend/src/pages/Login.test.jsx",

                    type:
                        "unit-test",

                    language:
                        "javascript",

                    content:
                        "describe('Login',()=>{});"

                }

            ]

        });

    if (!manifest)
        throw new Error("Manifest not created.");

    if (!manifest.manifestId)
        throw new Error("manifestId missing");

    if (!manifest.projectId)
        throw new Error("projectId missing");

    if (!manifest.executionId)
        throw new Error("executionId missing");

    if (!Array.isArray(manifest.artifacts))
        throw new Error("Artifacts missing");

    if (manifest.artifacts.length !== 3)
        throw new Error("Incorrect artifact count");

    console.log("✅ Build Manifest");

    for (const artifact of manifest.artifacts) {

        if (!artifact.path)
            throw new Error("Artifact path missing");

        if (!artifact.content)
            throw new Error("Artifact content missing");

    }

    console.log("✅ Source Files");

    console.log("\n══════════════════════════════════════");
    console.log(" BUILD SUMMARY");
    console.log("══════════════════════════════════════");

    console.log("Manifest:",
        manifest.manifestId);

    console.log("Project:",
        manifest.projectId);

    console.log("Execution:",
        manifest.executionId);

    console.log("Generated By:",
        manifest.generatedBy);

    console.log("Artifacts:",
        manifest.artifacts.length);

    for (const file of manifest.artifacts) {

        console.log(`  • ${file.path}`);

    }

    console.log("\n🎉 BUILD MANIFEST GENERATOR PASSED\n");

}
catch (error) {

    console.error("\n❌ BUILD MANIFEST GENERATOR FAILED\n");

    console.error(error);

    process.exit(1);

}